#: Approximate-nearest-neighbour index for similarity search. HNSW rather than IVFFlat
#: because IVFFlat must be built against existing rows to choose its list count, and this
#: index is created on an empty table.
VECTOR_INDEX = "ix_document_chunks_embedding_hnsw"

_MISSING_EXTENSION = (
    "The 'vector' extension is not installed in this database and could not be created. "
    "FINAGENT LAB stores embeddings in a vector(1536) column, so install pgvector "
    "(or grant the migration role CREATE privilege) and run 'alembic upgrade head' again. "
    "The pgvector/pgvector:pg16 image used by the development stack has it preinstalled."
)


def _has_pgvector() -> bool:
    return bool(
        op.get_bind().exec_driver_sql("SELECT 1 FROM pg_extension WHERE extname = 'vector'").first()
    )


def _vector_column_is_native() -> bool:
    """Whether the ORM will emit ``vector(1536)`` rather than falling back to JSON."""
    try:
        import pgvector.sqlalchemy  # noqa: F401
    except ImportError:
        return False
    return True


def upgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        Base.metadata.create_all(bind=bind)
        return

    try:
        op.execute("CREATE EXTENSION IF NOT EXISTS vector")
    except Exception as exc:  # noqa: BLE001 - reported below with a usable instruction
        if _vector_column_is_native():
            raise RuntimeError(_MISSING_EXTENSION) from exc

    if _vector_column_is_native() and not _has_pgvector():
        raise RuntimeError(_MISSING_EXTENSION)

    Base.metadata.create_all(bind=bind)

    if _has_pgvector():
        op.execute(
            f"CREATE INDEX IF NOT EXISTS {VECTOR_INDEX} "
            "ON document_chunks USING hnsw (embedding vector_cosine_ops)"
        )


def downgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name == "postgresql":
        op.execute(f"DROP INDEX IF EXISTS {VECTOR_INDEX}")
    Base.metadata.drop_all(bind=bind)
